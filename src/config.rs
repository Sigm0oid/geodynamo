//! Table, attribute, and S2 covering configuration for [`crate::GeoDataManager`].

use aws_sdk_dynamodb::Client;

/// Controls how 64-bit S2 cell IDs are serialized into DynamoDB `N` attributes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum GeohashEncoding {
    /// Unsigned 64-bit decimal representation (`0..=u64::MAX`), compatible with `dynamodb-geo.py` (`s2sphere`).
    #[default]
    Unsigned,
    /// Two's-complement signed 64-bit decimal representation (`i64::MIN..=i64::MAX`),
    /// compatible with AWS Labs' Java `awslabs/dynamodb-geo` and JavaScript `dynamodb-geo.js`.
    Signed,
}

/// Controls how coordinate strings are formatted inside the `geoJson` DynamoDB attribute.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum CoordinateFormat {
    /// Compact `"<latitude>,<longitude>"` format used by `dynamodb-geo.py`.
    #[default]
    LatLngCsv,
    /// Standard GeoJSON Point JSON object (`{"type":"Point","coordinates":[lng,lat]}`),
    /// compatible with Java `awslabs/dynamodb-geo` and JavaScript `dynamodb-geo.js`.
    GeoJsonPoint,
}

/// Configuration for a geospatial DynamoDB table and its Local Secondary Index.
#[derive(Debug, Clone)]
pub struct GeoDataManagerConfiguration {
    /// Official AWS SDK DynamoDB client.
    pub client: Client,
    /// Target DynamoDB table name.
    pub table_name: String,
    /// Partition key attribute name (`N`). Defaults to `"hashKey"`.
    pub hash_key_attribute_name: String,
    /// Sort key attribute name (`S`). Defaults to `"rangeKey"`.
    pub range_key_attribute_name: String,
    /// Full 64-bit S2 geohash attribute name (`N`). Defaults to `"geohash"`.
    pub geohash_attribute_name: String,
    /// Coordinate string attribute name (`S`). Defaults to `"geoJson"`.
    pub geojson_attribute_name: String,
    /// Local Secondary Index name over `(hashKey, geohash)`. Defaults to `"geohash-index"`.
    pub geohash_index_name: String,
    /// Number of leading base-10 digits of `geohash` used to compute `hashKey`. Defaults to `2`.
    pub hash_key_length: usize,
    /// Threshold for merging adjacent S2 cell ID ranges. Defaults to `2`.
    pub merge_threshold: u64,
    /// Maximum number of S2 cells generated by the region coverer per query. Defaults to `8`.
    pub max_cells: usize,
    /// Geohash integer sign encoding (`Unsigned` for Python compatibility, `Signed` for Java/JS).
    pub geohash_encoding: GeohashEncoding,
    /// Coordinate serialization format (`LatLngCsv` or `GeoJsonPoint`).
    pub coordinate_format: CoordinateFormat,
}

impl GeoDataManagerConfiguration {
    /// Default merge threshold between adjacent S2 geohash ranges.
    pub const DEFAULT_MERGE_THRESHOLD: u64 = 2;

    /// Creates a new configuration with standard `geodynamo` attribute names and defaults.
    pub fn new(client: Client, table_name: impl Into<String>) -> Self {
        Self {
            client,
            table_name: table_name.into(),
            hash_key_attribute_name: "hashKey".to_owned(),
            range_key_attribute_name: "rangeKey".to_owned(),
            geohash_attribute_name: "geohash".to_owned(),
            geojson_attribute_name: "geoJson".to_owned(),
            geohash_index_name: "geohash-index".to_owned(),
            hash_key_length: 2,
            merge_threshold: Self::DEFAULT_MERGE_THRESHOLD,
            max_cells: 8,
            geohash_encoding: GeohashEncoding::Unsigned,
            coordinate_format: CoordinateFormat::LatLngCsv,
        }
    }

    /// Configures compatibility defaults matching AWS Labs' Java `awslabs/dynamodb-geo` / `dynamodb-geo.js`
    /// (`hash_key_length = 6`, `GeohashEncoding::Signed`, and `CoordinateFormat::GeoJsonPoint`).
    #[must_use]
    pub fn with_java_js_defaults(mut self) -> Self {
        self.hash_key_length = 6;
        self.geohash_encoding = GeohashEncoding::Signed;
        self.coordinate_format = CoordinateFormat::GeoJsonPoint;
        self
    }

    /// Sets the number of leading decimal digits of the 64-bit geohash used as the partition key.
    #[must_use]
    pub fn with_hash_key_length(mut self, hash_key_length: usize) -> Self {
        self.hash_key_length = hash_key_length.max(1);
        self
    }

    /// Sets a custom partition key attribute name.
    #[must_use]
    pub fn with_hash_key_attribute_name(mut self, name: impl Into<String>) -> Self {
        self.hash_key_attribute_name = name.into();
        self
    }

    /// Sets a custom sort key attribute name.
    #[must_use]
    pub fn with_range_key_attribute_name(mut self, name: impl Into<String>) -> Self {
        self.range_key_attribute_name = name.into();
        self
    }

    /// Sets a custom geohash attribute name.
    #[must_use]
    pub fn with_geohash_attribute_name(mut self, name: impl Into<String>) -> Self {
        self.geohash_attribute_name = name.into();
        self
    }

    /// Sets a custom coordinate (`geoJson`) attribute name.
    #[must_use]
    pub fn with_geojson_attribute_name(mut self, name: impl Into<String>) -> Self {
        self.geojson_attribute_name = name.into();
        self
    }

    /// Sets a custom Local Secondary Index name.
    #[must_use]
    pub fn with_geohash_index_name(mut self, name: impl Into<String>) -> Self {
        self.geohash_index_name = name.into();
        self
    }

    /// Sets the maximum S2 cell budget used when covering a search rectangle or radius.
    #[must_use]
    pub fn with_max_cells(mut self, max_cells: usize) -> Self {
        self.max_cells = max_cells.max(1);
        self
    }

    /// Sets the geohash integer encoding (`Unsigned` or `Signed`).
    #[must_use]
    pub fn with_geohash_encoding(mut self, encoding: GeohashEncoding) -> Self {
        self.geohash_encoding = encoding;
        self
    }

    /// Sets the coordinate string serialization format (`LatLngCsv` or `GeoJsonPoint`).
    #[must_use]
    pub fn with_coordinate_format(mut self, format: CoordinateFormat) -> Self {
        self.coordinate_format = format;
        self
    }
}
